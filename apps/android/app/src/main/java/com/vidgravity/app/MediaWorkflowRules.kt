package com.vidgravity.app

internal object MediaWorkflowRules {
    fun mimeForName(name: String): String? = when (name.substringAfterLast('.', "").lowercase()) {
        "jpg", "jpeg" -> "image/jpeg"
        "png" -> "image/png"
        "webp" -> "image/webp"
        "mp4", "m4v" -> "video/mp4"
        "webm" -> "video/webm"
        "mkv" -> "video/x-matroska"
        "mp3" -> "audio/mpeg"
        "m4a" -> "audio/mp4"
        "wav" -> "audio/wav"
        "flac" -> "audio/flac"
        else -> null
    }

    fun supportsStory(mime: String): Boolean = mime.startsWith("video/") || mime.startsWith("audio/")
}
